// Build web/data/mystic-forge-recipes.js from the Guild Wars 2 wiki's Semantic MediaWiki data. No dependencies.
//
// The official GW2 API has no Mystic Forge recipes, so this reads them from the wiki's public query API
// (api.php?action=ask — structured data, not HTML scraping), resolves ingredient/output names to item or currency ids,
// and writes them in the /v2/recipes shape as an ES module the app imports.
//
// Being a good API citizen (https://www.mediawiki.org/wiki/API:Etiquette):
//  - identifies itself with a User-Agent that includes contact details (WIKI_CONTACT env var or REPOSITORY_URL)
//  - requests are strictly sequential, with a short pause between them
//  - sends `maxlag` so the wiki can ask us to back off when its servers are busy, and honours Retry-After
//  - runs rarely (weekly in CI) and the result is shipped as a static file, so app users never query the wiki
//
// Usage:  node tools/update-mystic-forge.mjs      (takes ~1-2 minutes)
//         WIKI_CONTACT="https://github.com/you/repo" node tools/update-mystic-forge.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  APP_VERSION,
  GW2_API_BASE_URL,
  GW2_API_SCHEMA_VERSION,
  REPOSITORY_URL,
} from "../web/src/config/constants.js";

const WIKI_API_URL = "https://wiki.guildwars2.com/api.php";
const OUTPUT_PATH = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "web",
  "data",
  "mystic-forge-recipes.js",
);

const CONTACT = process.env.WIKI_CONTACT || REPOSITORY_URL;
if (!CONTACT) {
  console.error(
    "Set WIKI_CONTACT (a URL or email the wiki admins can reach you at), or REPOSITORY_URL in web/src/config/constants.js.",
  );
  process.exit(1);
}
// MediaWiki's recommended format: <client>/<version> (<contact>) <library>/<version>
const REQUEST_HEADERS = {
  "User-Agent": `GW2Visualizer/${APP_VERSION} (${CONTACT}; fan-made recipe viewer) Node.js/${process.versions.node}`,
};

const REQUEST_TIMEOUT_MS = 240_000;
const PAUSE_BETWEEN_REQUESTS_MS = 300;
const MAXLAG_SECONDS = 5;
const MAX_ATTEMPTS = 6;

// The recipe query is heavy; small pages avoid wiki gateway timeouts. Name lookups use OR-queries, which the wiki
// rejects beyond ~10 conditions.
const RECIPE_PAGE_SIZE = 250;
const NAME_LOOKUP_BATCH_SIZE = 10;
const API_BATCH_SIZE = 200;
const COIN_CURRENCY_ID = 1;

const FILE_HEADER = [
  "// Generated by tools/update-mystic-forge.mjs. Do not edit by hand.",
  "//",
  "// Mystic Forge recipes derived from the Guild Wars 2 Wiki (https://wiki.guildwars2.com/). Contributor content on the",
  "// wiki is available under the GNU Free Documentation License 1.3 (see data/LICENSE-GFDL-1.3.txt); game content",
  "// remains © ArenaNet LLC. This file is not covered by the project's MIT license.",
  "",
].join("\n");

const log = (...parts) => console.log(...parts);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// ---------------------------------------------------------------- HTTP helpers

/**
 * Polite GET: one request at a time with a pause, retries honouring Retry-After (and the wiki's maxlag errors).
 * A 404 on an `ids=` query means "none of these exist" → [].
 */
async function fetchJson(url) {
  for (let attempt = 1; ; attempt++) {
    await sleep(PAUSE_BETWEEN_REQUESTS_MS);
    let waitMs = 2000 * attempt;
    try {
      const response = await fetch(url, {
        headers: REQUEST_HEADERS,
        signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
      });
      const retryAfterSeconds = Number(response.headers.get("Retry-After"));
      if (retryAfterSeconds > 0) waitMs = retryAfterSeconds * 1000;
      if (response.status === 404 && url.includes("ids=")) return [];
      if (!response.ok) throw new Error(`HTTP ${response.status} for ${url}`);
      const body = await response.json();
      if (body?.error?.code === "maxlag")
        throw new Error(`wiki busy (maxlag): ${body.error.info}`);
      if (body?.error)
        throw Object.assign(
          new Error(`wiki API error ${body.error.code}: ${body.error.info}`),
          { fatal: true },
        );
      return body;
    } catch (error) {
      if (error.fatal || attempt >= MAX_ATTEMPTS) throw error;
      log(`  retrying in ${Math.round(waitMs / 1000)}s (${error.message})`);
      await sleep(waitMs);
    }
  }
}

/** Run a Semantic MediaWiki #ask query, following `query-continue-offset` across pages. */
async function askWiki(query, { pageSize = 5000, showProgress = false } = {}) {
  const results = {};
  for (let offset = 0; ;) {
    const params = new URLSearchParams({
      action: "ask",
      format: "json",
      maxlag: String(MAXLAG_SECONDS),
      query: `${query}|limit=${pageSize}|offset=${offset}`,
    });
    const response = await fetchJson(`${WIKI_API_URL}?${params}`);
    Object.assign(results, response.query?.results || {});
    offset = response["query-continue-offset"];
    if (showProgress) log(`  ...${Object.keys(results).length}`);
    if (!offset) return results;
  }
}

const gw2ApiUrl = (endpoint, params) =>
  `${GW2_API_BASE_URL}${endpoint}?${new URLSearchParams({ ...params, v: GW2_API_SCHEMA_VERSION })}`;

async function fetchItems(itemIds) {
  const items = new Map();
  for (let start = 0; start < itemIds.length; start += API_BATCH_SIZE) {
    const batch = itemIds.slice(start, start + API_BATCH_SIZE).join(",");
    for (const item of await fetchJson(gw2ApiUrl("/items", { ids: batch })))
      items.set(item.id, item);
  }
  return items;
}

/** SMW record printouts look like {"Field": {"item": [value]}}; return the first value or null. */
const firstRecordValue = (record, fieldName) =>
  record?.[fieldName]?.item?.[0] ?? null;

// ---------------------------------------------------------------- steps

/**
 * @typedef {{ name: string | null, count: number, itemId: number | null }} WikiIngredient
 * @typedef {{ subobject: string, pageName: string, outputItemId: number | null, outputCount: number,
 *             forgeRecipeId: number | null, ingredients: WikiIngredient[] }} WikiRecipe
 */

/** @returns {Promise<WikiRecipe[]>} */
async function fetchWikiRecipes() {
  log("Querying the wiki for Mystic Forge recipes (~1 min)...");
  const rawResults = await askWiki(
    "[[Has recipe source::Mystic forge]]|?Has output game id|?Has output quantity|?Has ingredient" +
      "|?Has ingredient with id|?Has mystic forge id",
    { pageSize: RECIPE_PAGE_SIZE, showProgress: true },
  );
  log(`  ${Object.keys(rawResults).length} recipes`);

  return Object.entries(rawResults).map(([subobject, result]) => {
    const printouts = result.printouts;
    // "Has ingredient with id" only lists ingredients whose id is known; key them by position.
    const idsByPosition = new Map(
      (printouts["Has ingredient with id"] || []).map((record) => [
        firstRecordValue(record, "Has ingredient index"),
        firstRecordValue(record, "Has ingredient id"),
      ]),
    );
    const ingredientRecords = [...(printouts["Has ingredient"] || [])].sort(
      (a, b) =>
        (firstRecordValue(a, "Has ingredient index") || 0) -
        (firstRecordValue(b, "Has ingredient index") || 0),
    );
    return {
      subobject,
      pageName: subobject.split("#")[0],
      outputItemId: printouts["Has output game id"]?.[0] ?? null,
      outputCount: printouts["Has output quantity"]?.[0] ?? 1,
      forgeRecipeId: printouts["Has mystic forge id"]?.[0] ?? null,
      ingredients: ingredientRecords.map((record) => ({
        name: firstRecordValue(record, "Has ingredient name")?.fulltext ?? null,
        count: firstRecordValue(record, "Has ingredient quantity") || 1,
        itemId:
          idsByPosition.get(firstRecordValue(record, "Has ingredient index")) ??
          null,
      })),
    };
  });
}

/**
 * Map wiki page names to ['Currency' | 'Item', id]. Unresolvable names (e.g. "Charm (ingredient)") are omitted.
 * @param {Set<string>} names
 * @returns {Promise<Map<string, ['Currency' | 'Item', number]>>}
 */
async function resolveNames(names) {
  log(`Resolving ${names.size} names without IDs...`);
  const currencies = await fetchJson(gw2ApiUrl("/currencies", { ids: "all" }));
  const currencyIds = new Map(
    currencies.map((c) => [c.name.toLowerCase(), c.id]),
  );
  if (!currencyIds.has("coin")) currencyIds.set("coin", COIN_CURRENCY_ID);

  const resolved = new Map();
  const itemNames = [];
  for (const name of names) {
    if (currencyIds.has(name.toLowerCase()))
      resolved.set(name, ["Currency", currencyIds.get(name.toLowerCase())]);
    else itemNames.push(name);
  }

  // A wiki page can list several game ids (variants); collect them all, then pick the best match below.
  const candidateIdsByName = new Map();
  for (
    let start = 0;
    start < itemNames.length;
    start += NAME_LOOKUP_BATCH_SIZE
  ) {
    const batch = itemNames.slice(start, start + NAME_LOOKUP_BATCH_SIZE);
    const results = await askWiki(
      `${batch.map((name) => `[[${name}]]`).join(" OR ")}|?Has game id`,
    );
    for (const [pageName, result] of Object.entries(results)) {
      const ids = (result.printouts["Has game id"] || [])
        .filter((value) => /^\d+$/.test(String(value)))
        .map(Number);
      if (ids.length) candidateIdsByName.set(pageName, ids);
    }
  }

  const items = await fetchItems(
    [...new Set([...candidateIdsByName.values()].flat())].sort((a, b) => a - b),
  );
  for (const [pageName, candidateIds] of candidateIdsByName) {
    // Prefer ids whose API name equals the page name (minus any "(disambiguation)"), then any live id.
    const plainName = pageName.replace(/\s*\(.*\)$/, "").toLowerCase();
    const liveIds = candidateIds.filter((id) => items.has(id));
    const exactIds = liveIds.filter(
      (id) => items.get(id).name.toLowerCase() === plainName,
    );
    const best = exactIds.length
      ? exactIds
      : liveIds.length
        ? liveIds
        : candidateIds;
    resolved.set(pageName, ["Item", Math.min(...best)]);
  }

  log(`  resolved ${resolved.size}/${names.size}`);
  return resolved;
}

/** Convert to /v2/recipes-shaped objects. Ingredients that can't be resolved become `Named` placeholders. */
function toApiRecipes(wikiRecipes, resolved) {
  const apiRecipes = [];
  let skipped = 0;
  for (const recipe of wikiRecipes) {
    let outputItemId = recipe.outputItemId;
    if (!outputItemId && resolved.get(recipe.pageName)?.[0] === "Item")
      outputItemId = resolved.get(recipe.pageName)[1];
    if (!outputItemId) {
      skipped++;
      continue;
    }

    const ingredients = recipe.ingredients.map((ingredient) => {
      if (ingredient.itemId)
        return {
          type: "Item",
          id: Number(ingredient.itemId),
          count: ingredient.count,
        };
      if (resolved.has(ingredient.name)) {
        const [kind, entityId] = resolved.get(ingredient.name);
        return { type: kind, id: entityId, count: ingredient.count };
      }
      return { type: "Named", name: ingredient.name, count: ingredient.count };
    });

    apiRecipes.push({
      id: `mf${recipe.forgeRecipeId || apiRecipes.length}`,
      type: "MysticForge",
      output_item_id: Number(outputItemId),
      output_item_count: recipe.outputCount,
      disciplines: ["Mystic Forge"],
      min_rating: 0,
      ingredients,
      wiki: recipe.subobject,
    });
  }
  apiRecipes.sort(
    (a, b) =>
      a.output_item_id - b.output_item_id ||
      (a.wiki < b.wiki ? -1 : a.wiki > b.wiki ? 1 : 0),
  );
  return { apiRecipes, skipped };
}

/**
 * Existing recipes, to avoid rewriting (and churning the weekly PR) when nothing changed. Imported rather than
 * parsed as JSON, so it still works if the file was reformatted by hand.
 */
async function readExistingRecipes() {
  if (!existsSync(OUTPUT_PATH)) return null;
  try {
    return (await import(pathToFileURL(OUTPUT_PATH).href)).default.recipes;
  } catch {
    return null;
  }
}

/** The file as this tool writes it: our header, then the whole payload on one line (not reformatted). */
function isGeneratedLayout(source) {
  return (
    source.startsWith(FILE_HEADER) &&
    source.slice(FILE_HEADER.length).split("\n").length === 2
  );
}

function writeModule(apiRecipes) {
  const payload = {
    generated: new Date().toISOString().replace(/\.\d{3}Z$/, "Z"),
    source: "https://wiki.guildwars2.com/",
    license: "GFDL-1.3 (wiki contributor content); game content © ArenaNet LLC",
    recipes: apiRecipes,
  };
  writeFileSync(
    OUTPUT_PATH,
    `${FILE_HEADER}export default ${JSON.stringify(payload)};\n`,
  );
}

log(`User-Agent: ${REQUEST_HEADERS["User-Agent"]}`);
const wikiRecipes = await fetchWikiRecipes();
const unresolvedNames = new Set([
  ...wikiRecipes
    .filter((recipe) => !recipe.outputItemId)
    .map((recipe) => recipe.pageName),
  ...wikiRecipes.flatMap((recipe) =>
    recipe.ingredients.filter((i) => !i.itemId && i.name).map((i) => i.name),
  ),
]);
const resolved = await resolveNames(unresolvedNames);
const { apiRecipes, skipped } = toApiRecipes(wikiRecipes, resolved);

if (
  JSON.stringify(await readExistingRecipes()) === JSON.stringify(apiRecipes) &&
  isGeneratedLayout(readFileSync(OUTPUT_PATH, "utf8"))
) {
  log(
    `No changes: ${apiRecipes.length} recipes, web/data/mystic-forge-recipes.js left untouched`,
  );
} else {
  writeModule(apiRecipes);
  log(
    `Wrote ${apiRecipes.length} recipes to web/data/mystic-forge-recipes.js (${skipped} skipped: output not resolvable)`,
  );
}
